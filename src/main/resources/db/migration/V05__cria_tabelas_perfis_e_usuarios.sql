create table perfis (
    id integer generated by default as identity,
    nome varchar(30) not null,
    primary key (id),
    constraint uk_perfis_nome unique (nome)
);

insert into perfis (nome) values ('ADMIN'), ('ATENDENTE'), ('CLIENTE');

create table usuarios (
    id integer generated by default as identity,
    login varchar(100) not null,
    senha varchar(100) not null,
    ativo boolean not null default true,
    cliente_id integer,
    primary key (id),
    constraint uk_usuarios_login unique (login),
    constraint uk_usuarios_cliente unique (cliente_id),
    constraint fk_usuarios_cliente foreign key (cliente_id) references clientes (id)
);

create table usuario_perfis (
    usuario_id integer not null,
    perfil_id integer not null,
    primary key (usuario_id, perfil_id),
    constraint fk_usuario_perfis_usuario foreign key (usuario_id) references usuarios (id) on delete cascade,
    constraint fk_usuario_perfis_perfil foreign key (perfil_id) references perfis (id)
);
